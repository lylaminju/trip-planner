create table if not exists public.trips (
  id bigint generated by default as identity primary key,
  created_by uuid references auth.users(id) on delete set null,
  name text not null,
  destination text not null,
  start_date date,
  end_date date,
  timezone text not null default 'America/Toronto',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint trips_date_range_valid check (
    start_date is null or end_date is null or start_date <= end_date
  ),
  constraint trips_destination_not_blank check (btrim(destination) <> ''),
  constraint trips_timezone_not_blank check (btrim(timezone) <> '')
);

alter table public.trips
  add column if not exists destination text;

alter table public.trips
  alter column destination set not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'trips_destination_not_blank'
      and conrelid = 'public.trips'::regclass
  ) then
    alter table public.trips
      add constraint trips_destination_not_blank
      check (btrim(destination) <> '');
  end if;
end;
$$;

create table if not exists public.trip_memberships (
  trip_id bigint not null references public.trips(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'editor', 'viewer')),
  created_at timestamptz not null default now(),
  primary key (trip_id, user_id)
);

create table if not exists public.places (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(id) on delete cascade,
  name text not null,
  address text,
  google_maps_url text not null,
  place_id text,
  google_place_token text,
  google_internal_ids text,
  source_list_url text,
  latitude double precision not null,
  longitude double precision not null,
  notes text,
  links text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.places
  add column if not exists links text[] not null default '{}';

alter table public.places
  add column if not exists trip_id bigint references public.trips(id) on delete cascade;

create table if not exists public.itinerary_items (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(id) on delete cascade,
  place_id bigint not null references public.places(id) on delete cascade,
  visit_date text,
  visit_time text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.itinerary_items
  add column if not exists trip_id bigint references public.trips(id) on delete cascade;

create table if not exists public.route_segments (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(id) on delete cascade,
  from_item_id bigint not null references public.itinerary_items(id) on delete cascade,
  to_item_id bigint not null references public.itinerary_items(id) on delete cascade,
  mode text not null default 'walking' check (mode in ('walking', 'transit', 'bicycling', 'driving')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.route_segments
  add column if not exists trip_id bigint references public.trips(id) on delete cascade;

create table if not exists public.route_geometry_cache (
  cache_key text primary key,
  from_place_id bigint not null references public.places(id) on delete cascade,
  to_place_id bigint not null references public.places(id) on delete cascade,
  mode text not null check (mode in ('walking', 'transit', 'bicycling', 'driving')),
  from_latitude double precision not null,
  from_longitude double precision not null,
  to_latitude double precision not null,
  to_longitude double precision not null,
  status text not null check (status in ('ok', 'no_route')),
  encoded_polyline text,
  duration_seconds integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.route_geometry_cache
  add column if not exists duration_seconds integer;

create index if not exists idx_itinerary_items_visit_date_time
  on public.itinerary_items (trip_id, visit_date, visit_time, place_id);

create index if not exists idx_route_segments_from_to
  on public.route_segments (trip_id, from_item_id, to_item_id);

create index if not exists idx_route_geometry_cache_places
  on public.route_geometry_cache (from_place_id, to_place_id, mode);

create index if not exists idx_places_trip_name
  on public.places (trip_id, name);

create index if not exists idx_trip_memberships_user
  on public.trip_memberships (user_id, trip_id);

