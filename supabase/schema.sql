create or replace function public.reset_trip_planner_id_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform setval(pg_get_serial_sequence('public.trips', 'id'), coalesce((select max(id) from public.trips), 1), true);
  perform setval(pg_get_serial_sequence('public.places', 'id'), coalesce((select max(id) from public.places), 1), true);
  perform setval(pg_get_serial_sequence('public.itinerary_items', 'id'), coalesce((select max(id) from public.itinerary_items), 1), true);
  perform setval(pg_get_serial_sequence('public.route_segments', 'id'), coalesce((select max(id) from public.route_segments), 1), true);
end;
$$;

grant execute on function public.reset_trip_planner_id_sequences() to service_role;

